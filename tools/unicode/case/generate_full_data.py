#!/usr/bin/env python3
"""Generate Unicode 17 full case-mapping data from SpecialCasing.txt.

Usage:
    generate_full_data.py SpecialCasing.txt UnicodeData.txt output.zig

The generated table stores every non-simple mapping as a record. Records keep
their SpecialCasing.txt order for equal code points, so locale-specific entries
can be preferred over generic entries by the runtime lookup.

Two raw bitmaps (full_lower.bin, full_upper.bin) are written next to the Zig
output. A clear bit means the code point maps to itself for that case kind in
the root locale, letting the hot path copy the source bytes untouched.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

INPUT_SHA256 = "efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588"
UNICODE_DATA_SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"

INTEREST_PAGE_LIMIT = 0x10000

LOCALE_BITS = {
    "tr": 2,
    "az": 2,
    "lt": 4,
}
CONDITION_BITS = {
    "final_sigma": 1,
    "after_soft_dotted": 2,
    "more_above": 4,
    "before_dot": 8,
    "not_before_dot": 16,
    "after_i": 32,
}


def checked_text(path: Path, expected_sha256: str = INPUT_SHA256) -> str:
    data = path.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != expected_sha256:
        raise SystemExit(
            f"{path}: expected Unicode 17 source SHA-256 {expected_sha256}, "
            f"found {actual}"
        )
    return data.decode("utf-8")


def parse_simple_interest(text: str) -> tuple[set[int], set[int]]:
    lower: set[int] = set()
    upper: set[int] = set()
    for line_number, line in enumerate(text.splitlines(), 1):
        fields = line.split(";")
        if len(fields) < 15:
            raise SystemExit(f"UnicodeData line {line_number}: malformed row")
        codepoint = int(fields[0], 16)
        if fields[12] and int(fields[12], 16) != codepoint:
            upper.add(codepoint)
        if fields[13] and int(fields[13], 16) != codepoint:
            lower.add(codepoint)
        if fields[14] and int(fields[14], 16) != codepoint:
            # Titlecase defaults to the uppercase mapping, so an explicit
            # title mapping also marks the code point for the upper bitmap.
            upper.add(codepoint)
    return lower, upper


def parse_mapping(field: str) -> list[int]:
    field = field.strip()
    if not field:
        return []
    return [int(token, 16) for token in field.split()]


def parse_conditions(field: str) -> tuple[int, int]:
    locale = 1
    conditions = 0
    for token in field.split():
        token = token.lower()
        if token in LOCALE_BITS:
            locale = LOCALE_BITS[token]
        elif token in CONDITION_BITS:
            conditions |= CONDITION_BITS[token]
        else:
            raise SystemExit(f"unknown SpecialCasing condition: {token}")
    return locale, conditions


def parse_records(text: str) -> tuple[list[tuple], list[int]]:
    components: list[int] = []
    records: list[tuple] = []
    for line_number, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [field.strip() for field in line.split(";")]
        if len(fields) < 4:
            raise SystemExit(f"SpecialCasing line {line_number}: malformed row")
        codepoint = int(fields[0], 16)
        lower = parse_mapping(fields[1])
        title = parse_mapping(fields[2])
        upper = parse_mapping(fields[3])
        locale, conditions = parse_conditions(fields[4] if len(fields) > 4 else "")

        def append(mapping: list[int]) -> tuple[int, int]:
            if not mapping:
                return 0, 0
            offset = len(components)
            components.extend(mapping)
            return offset, len(mapping)

        lower_offset, lower_len = append(lower)
        title_offset, title_len = append(title)
        upper_offset, upper_len = append(upper)
        records.append(
            (
                codepoint,
                locale,
                conditions,
                lower_offset,
                lower_len,
                title_offset,
                title_len,
                upper_offset,
                upper_len,
            )
        )
    if not records:
        raise SystemExit("missing SpecialCasing entries")
    # Stable sort keeps file order for equal code points.
    records.sort(key=lambda record: record[0])
    return records, components


def render(
    records: list[tuple],
    components: list[int],
    lower_interest: set[int],
    upper_interest: set[int],
) -> tuple[str, bytes, bytes]:
    lines = [
        "// Generated by tools/unicode/case/generate_full_data.py from Unicode 17.0.0.",
        f"// SpecialCasing.txt SHA-256: {INPUT_SHA256}",
        f"// UnicodeData.txt SHA-256: {UNICODE_DATA_SHA256}",
        "",
        "pub const Kind = enum(u2) { lower, title, upper };",
        "",
        "pub const Record = struct {",
        "    codepoint: u21,",
        "    locale: u3,",
        "    conditions: u6,",
        "    lower_offset: u16,",
        "    lower_len: u8,",
        "    title_offset: u16,",
        "    title_len: u8,",
        "    upper_offset: u16,",
        "    upper_len: u8,",
        "};",
        "",
        "pub const components = [_]u21{",
    ]
    for index in range(0, len(components), 8):
        chunk = components[index : index + 8]
        values = ", ".join(f"0x{value:x}" for value in chunk)
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            "",
            "pub const records = [_]Record{",
        ]
    )
    for record in records:
        (
            codepoint,
            locale,
            conditions,
            lower_offset,
            lower_len,
            title_offset,
            title_len,
            upper_offset,
            upper_len,
        ) = record
        lines.append(
            "    .{ "
            f".codepoint = 0x{codepoint:x}, .locale = {locale}, "
            f".conditions = {conditions}, "
            f".lower_offset = {lower_offset}, .lower_len = {lower_len}, "
            f".title_offset = {title_offset}, .title_len = {title_len}, "
            f".upper_offset = {upper_offset}, .upper_len = {upper_len} "
            "},"
        )
    lines.extend(["};", ""])
    # Every SpecialCasing record lives below U+10000, so a 256-entry page
    # index replaces the full-array binary search with a page-local one.
    page_limit = 0x100
    page_index = []
    record_index = 0
    for page in range(page_limit):
        page_start = page << 8
        while (record_index < len(records) and
               records[record_index][0] < page_start):
            record_index += 1
        page_index.append(record_index)
    if any(record[0] >> 8 >= page_limit for record in records):
        raise SystemExit("full case records exceed the page index")
    lines.extend(["const page_limit = 0x100;", "const page_index = [_]u16{"])
    for start in range(0, len(page_index), 16):
        chunk = ", ".join(str(value) for value in page_index[start : start + 16])
        lines.append(f"    {chunk},")
    lines.extend(["};", ""])

    # A flat bitmap answers "does this scalar have a root record?" in one
    # load; locale-only records (I, i, Lithuanian letters) are a tiny switch
    # so the common root case never pays for them.
    records_bitmap = bytearray(INTEREST_PAGE_LIMIT >> 3)
    for record in records:
        if record[0] >= INTEREST_PAGE_LIMIT or record[1] != 1:
            continue
        records_bitmap[record[0] >> 3] |= 1 << (record[0] & 7)

    lines.extend(
        [
            'const records_bmp = @embedFile("full_records.bin");',
            "",
            "/// True when `codepoint` has a SpecialCasing record for the",
            "/// requested locale family. Root lookups also accept root records.",
            "pub inline fn hasRecords(codepoint: u21, root_only: bool) bool {",
            "    if (codepoint >= 0x10000) return false;",
            "    if (records_bmp[codepoint >> 3] &",
            "        (@as(u8, 1) << @intCast(codepoint & 7)) != 0) return true;",
            "    if (!root_only) return localeOnlyRecord(codepoint);",
            "    return false;",
            "}",
            "",
        ]
    )

    # Per-kind identity bitmaps: a clear bit means the simple and full root
    # mappings are both the identity, so the caller can copy the source bytes.
    # Astral code points stay conservative and always take the table path.
    root_record_cps = {
        record[0]
        for record in records
        if record[0] < INTEREST_PAGE_LIMIT and record[1] == 1
    }
    lower_set = set(lower_interest) | root_record_cps
    upper_set = set(upper_interest) | root_record_cps
    lower_bitmap = bytearray(INTEREST_PAGE_LIMIT >> 3)
    upper_bitmap = bytearray(INTEREST_PAGE_LIMIT >> 3)
    for codepoint in lower_set:
        if codepoint < INTEREST_PAGE_LIMIT:
            lower_bitmap[codepoint >> 3] |= 1 << (codepoint & 7)
    for codepoint in upper_set:
        if codepoint < INTEREST_PAGE_LIMIT:
            upper_bitmap[codepoint >> 3] |= 1 << (codepoint & 7)

    # Lead-byte tables let the streaming path validate and copy a whole
    # identity sequence without decoding it. `lead_bounds` packs the minimum
    # and maximum valid second byte plus the sequence length; `*_lead_skip`
    # marks leads whose entire scalar range is identity for that kind.
    lead_bounds = [0] * 256
    for lead in range(0xC2, 0xF5):
        if lead < 0xE0:
            length, min_second, max_second = 2, 0x80, 0xBF
        elif lead < 0xF0:
            length = 3
            min_second = 0xA0 if lead == 0xE0 else 0x80
            max_second = 0x9F if lead == 0xED else 0xBF
        else:
            length = 4
            min_second = 0x90 if lead == 0xF0 else 0x80
            max_second = 0x8F if lead == 0xF4 else 0xBF
        lead_bounds[lead] = min_second | (max_second << 8) | (length << 16)

    def lead_skip_mask(interesting: set[int]) -> bytearray:
        mask = bytearray(32)
        for lead in range(0xC2, 0xF0):
            bounds = lead_bounds[lead]
            min_second = bounds & 0xFF
            max_second = (bounds >> 8) & 0xFF
            length = (bounds >> 16) & 7
            if length == 2:
                low = ((lead & 0x1F) << 6) | (min_second & 0x3F)
                high = ((lead & 0x1F) << 6) | (max_second & 0x3F)
            else:
                shift = 6 if length == 3 else 12
                tail = 0x3F if length == 3 else 0xFFF
                low = ((lead & 0x0F) << 12) | ((min_second & 0x3F) << shift)
                high = ((lead & 0x0F) << 12) | ((max_second & 0x3F) << shift) | tail
            if not any(low <= codepoint <= high for codepoint in interesting):
                mask[lead >> 3] |= 1 << (lead & 7)
        # Astral code points are always treated as interesting at runtime, so
        # four-byte leads never skip.
        return mask

    lower_skip = lead_skip_mask(lower_set)
    upper_skip = lead_skip_mask(upper_set)

    lines.extend(
        [
            'const lower_interest = @embedFile("full_lower.bin");',
            'const upper_interest = @embedFile("full_upper.bin");',
            "",
            "/// True when `codepoint` may map under `kind` for the requested locale",
            "/// family. A false result means the mapping is the identity.",
            "pub inline fn interesting(",
            "    codepoint: u21,",
            "    comptime kind: Kind,",
            "    root: bool,",
            ") bool {",
            "    if (codepoint >= 0x10000) return true;",
            "    const bitmap = switch (kind) {",
            "        .lower => lower_interest,",
            "        .title, .upper => upper_interest,",
            "    };",
            "    const bit = @as(u8, 1) << @intCast(codepoint & 7);",
            "    if (bitmap[codepoint >> 3] & bit != 0) return true;",
            "    if (!root) return localeOnlyRecord(codepoint);",
            "    return false;",
            "}",
            "",
            "/// Packed UTF-8 lead-byte metadata: minimum and maximum valid second",
            "/// byte in the low 16 bits, sequence length in bits 16..18.",
            "pub const lead_bounds = [_]u32{",
        ]
    )
    for start in range(0, 256, 16):
        chunk = ", ".join(f"0x{value:x}" for value in lead_bounds[start : start + 16])
        lines.append(f"    {chunk},")
    lines.extend(["};", ""])

    def emit_skip(name: str, mask: bytearray) -> None:
        chunk = ", ".join(str(value) for value in mask)
        lines.extend([f"pub const {name} = [_]u8{{{chunk}}};", ""])

    emit_skip("lower_lead_skip", lower_skip)
    emit_skip("upper_lead_skip", upper_skip)
    lines.extend(
        [
            "/// A lead can be skipped while folding only when neither case kind",
            "/// maps inside its range.",
            "pub const fold_lead_skip = blk: {",
            "    var mask: [32]u8 = undefined;",
            "    for (&mask, 0..) |*byte, index| {",
            "        byte.* = lower_lead_skip[index] & upper_lead_skip[index];",
            "    }",
            "    break :blk mask;",
            "};",
            "",
        ]
    )
    lines.extend(
        [
            "/// SpecialCasing entries that only exist for the Turkic or Lithuanian",
            "/// locale families; the root bitmap excludes them on purpose.",
            "inline fn localeOnlyRecord(codepoint: u21) bool {",
            "    return switch (codepoint) {",
            "        0x49, 0x4a, 0x69, 0xcc, 0xcd, 0x128, 0x12e, 0x307 => true,",
            "        else => false,",
            "    };",
            "}",
            "",
        ]
    )
    lines.extend(
        [
            "pub fn componentsFor(record: Record, kind: Kind) []const u21 {",
            "    const offset, const len = switch (kind) {",
            "        .lower => .{ record.lower_offset, record.lower_len },",
            "        .title => .{ record.title_offset, record.title_len },",
            "        .upper => .{ record.upper_offset, record.upper_len },",
            "    };",
            "    if (len == 0) return &.{};",
            "    return components[offset..][0..len];",
            "}",
            "",
            "/// Return every SpecialCasing record for one code point in file order.",
            "pub fn recordsFor(codepoint: u21) []const Record {",
            "    const page = codepoint >> 8;",
            "    if (page >= page_limit) return records[0..0];",
            "    var low: usize = page_index[page];",
            "    const high: usize = if (page + 1 < page_limit)",
            "        page_index[page + 1]",
            "    else",
            "        records.len;",
            "    var scan_high = high;",
            "    while (low < scan_high) {",
            "        const mid = low + (scan_high - low) / 2;",
            "        if (records[mid].codepoint < codepoint) {",
            "            low = mid + 1;",
            "        } else {",
            "            scan_high = mid;",
            "        }",
            "    }",
            "    const start = low;",
            "    scan_high = high;",
            "    while (low < scan_high) {",
            "        const mid = low + (scan_high - low) / 2;",
            "        if (records[mid].codepoint <= codepoint) {",
            "            low = mid + 1;",
            "        } else {",
            "            scan_high = mid;",
            "        }",
            "    }",
            "    return records[start..low];",
            "}",
            "",
            'test "generated full case mappings" {',
            '    const testing = @import("std").testing;',
            "    var found_upper = false;",
            "    for (recordsFor(0x00df)) |record| {",
            "        if (record.locale == 1 and record.conditions == 0) {",
            "            try testing.expectEqualSlices(",
            "                u21,",
            "                &.{ 'S', 'S' },",
            "                componentsFor(record, .upper),",
            "            );",
            "            found_upper = true;",
            "        }",
            "    }",
            "    try testing.expect(found_upper);",
            "    try testing.expectEqual(@as(usize, 0), recordsFor(0x0041).len);",
            "    try testing.expect(hasRecords(0x00df, true));",
            "    try testing.expect(hasRecords(0x03a3, true));",
            "    try testing.expect(!hasRecords(0x0041, false));",
            "    try testing.expect(!hasRecords(0x0049, true));",
            "    try testing.expect(hasRecords(0x0049, false));",
            "    try testing.expect(!hasRecords(0x4e00, false));",
            "    try testing.expect(!hasRecords(0x10400, false));",
            "    try testing.expect(interesting(0x00df, .lower, true));",
            "    try testing.expect(interesting(0x03a3, .lower, true));",
            "    try testing.expect(interesting('A', .lower, true));",
            "    try testing.expect(!interesting('a', .lower, true));",
            "    try testing.expect(interesting('a', .upper, true));",
            "    try testing.expect(!interesting(0x4e00, .lower, true));",
            "    try testing.expect(!interesting(0x00e9, .lower, true));",
            "    try testing.expect(interesting(0x00e9, .upper, true));",
            "    try testing.expect(interesting(0x0049, .lower, false));",
            "    try testing.expect(!interesting(0x007f, .lower, false));",
            "}",
            "",
        ]
    )
    return (
        "\n".join(lines),
        bytes(lower_bitmap),
        bytes(upper_bitmap),
        bytes(records_bitmap),
    )


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    input_path = Path(sys.argv[1])
    unicode_path = Path(sys.argv[2])
    output_path = Path(sys.argv[3])
    records, components = parse_records(checked_text(input_path))
    lower_interest, upper_interest = parse_simple_interest(
        checked_text(unicode_path, UNICODE_DATA_SHA256)
    )
    text, lower_bitmap, upper_bitmap, records_bitmap = render(
        records,
        components,
        lower_interest,
        upper_interest,
    )
    output_path.write_text(text, encoding="utf-8")
    directory = output_path.parent
    (directory / "full_lower.bin").write_bytes(lower_bitmap)
    (directory / "full_upper.bin").write_bytes(upper_bitmap)
    (directory / "full_records.bin").write_bytes(records_bitmap)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
