#!/usr/bin/env python3
"""Generate Unicode 17 full case-mapping data from SpecialCasing.txt.

Usage:
    generate_full_data.py SpecialCasing.txt src/unicode/case/full_data.zig

The generated table stores every non-simple mapping as a record. Records keep
their SpecialCasing.txt order for equal code points, so locale-specific entries
can be preferred over generic entries by the runtime lookup.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

INPUT_SHA256 = "efc25faf19de21b92c1194c111c932e03d2a5eaf18194e33f1156e96de4c9588"

LOCALE_BITS = {
    "tr": 2,
    "az": 2,
    "lt": 4,
}
CONDITION_BITS = {
    "final_sigma": 1,
    "after_soft_dotted": 2,
    "more_above": 4,
    "before_dot": 8,
    "not_before_dot": 16,
    "after_i": 32,
}


def checked_text(path: Path) -> str:
    data = path.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != INPUT_SHA256:
        raise SystemExit(
            f"{path}: expected Unicode 17 source SHA-256 {INPUT_SHA256}, "
            f"found {actual}"
        )
    return data.decode("utf-8")


def parse_mapping(field: str) -> list[int]:
    field = field.strip()
    if not field:
        return []
    return [int(token, 16) for token in field.split()]


def parse_conditions(field: str) -> tuple[int, int]:
    locale = 1
    conditions = 0
    for token in field.split():
        token = token.lower()
        if token in LOCALE_BITS:
            locale = LOCALE_BITS[token]
        elif token in CONDITION_BITS:
            conditions |= CONDITION_BITS[token]
        else:
            raise SystemExit(f"unknown SpecialCasing condition: {token}")
    return locale, conditions


def parse_records(text: str) -> tuple[list[tuple], list[int]]:
    components: list[int] = []
    records: list[tuple] = []
    for line_number, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [field.strip() for field in line.split(";")]
        if len(fields) < 4:
            raise SystemExit(f"SpecialCasing line {line_number}: malformed row")
        codepoint = int(fields[0], 16)
        lower = parse_mapping(fields[1])
        title = parse_mapping(fields[2])
        upper = parse_mapping(fields[3])
        locale, conditions = parse_conditions(fields[4] if len(fields) > 4 else "")

        def append(mapping: list[int]) -> tuple[int, int]:
            if not mapping:
                return 0, 0
            offset = len(components)
            components.extend(mapping)
            return offset, len(mapping)

        lower_offset, lower_len = append(lower)
        title_offset, title_len = append(title)
        upper_offset, upper_len = append(upper)
        records.append(
            (
                codepoint,
                locale,
                conditions,
                lower_offset,
                lower_len,
                title_offset,
                title_len,
                upper_offset,
                upper_len,
            )
        )
    if not records:
        raise SystemExit("missing SpecialCasing entries")
    # Stable sort keeps file order for equal code points.
    records.sort(key=lambda record: record[0])
    return records, components


def render(records: list[tuple], components: list[int]) -> str:
    lines = [
        "// Generated by tools/unicode/case/generate_full_data.py from Unicode 17.0.0.",
        f"// SpecialCasing.txt SHA-256: {INPUT_SHA256}",
        "",
        "pub const Kind = enum(u2) { lower, title, upper };",
        "",
        "pub const Record = struct {",
        "    codepoint: u21,",
        "    locale: u3,",
        "    conditions: u6,",
        "    lower_offset: u16,",
        "    lower_len: u8,",
        "    title_offset: u16,",
        "    title_len: u8,",
        "    upper_offset: u16,",
        "    upper_len: u8,",
        "};",
        "",
        "pub const components = [_]u21{",
    ]
    for index in range(0, len(components), 8):
        chunk = components[index : index + 8]
        values = ", ".join(f"0x{value:x}" for value in chunk)
        lines.append(f"    {values},")
    lines.extend(
        [
            "};",
            "",
            "pub const records = [_]Record{",
        ]
    )
    for record in records:
        (
            codepoint,
            locale,
            conditions,
            lower_offset,
            lower_len,
            title_offset,
            title_len,
            upper_offset,
            upper_len,
        ) = record
        lines.append(
            "    .{ "
            f".codepoint = 0x{codepoint:x}, .locale = {locale}, "
            f".conditions = {conditions}, "
            f".lower_offset = {lower_offset}, .lower_len = {lower_len}, "
            f".title_offset = {title_offset}, .title_len = {title_len}, "
            f".upper_offset = {upper_offset}, .upper_len = {upper_len} "
            "},"
        )
    lines.extend(
        [
            "};",
            "",
            "pub fn componentsFor(record: Record, kind: Kind) []const u21 {",
            "    const offset, const len = switch (kind) {",
            "        .lower => .{ record.lower_offset, record.lower_len },",
            "        .title => .{ record.title_offset, record.title_len },",
            "        .upper => .{ record.upper_offset, record.upper_len },",
            "    };",
            "    if (len == 0) return &.{};",
            "    return components[offset..][0..len];",
            "}",
            "",
            "/// Return every SpecialCasing record for one code point in file order.",
            "pub fn recordsFor(codepoint: u21) []const Record {",
            "    var low: usize = 0;",
            "    var high = records.len;",
            "    while (low < high) {",
            "        const mid = low + (high - low) / 2;",
            "        if (records[mid].codepoint < codepoint) {",
            "            low = mid + 1;",
            "        } else {",
            "            high = mid;",
            "        }",
            "    }",
            "    const start = low;",
            "    high = records.len;",
            "    while (low < high) {",
            "        const mid = low + (high - low) / 2;",
            "        if (records[mid].codepoint <= codepoint) {",
            "            low = mid + 1;",
            "        } else {",
            "            high = mid;",
            "        }",
            "    }",
            "    return records[start..low];",
            "}",
            "",
            'test "generated full case mappings" {',
            '    const testing = @import("std").testing;',
            "    var found_upper = false;",
            "    for (recordsFor(0x00df)) |record| {",
            "        if (record.locale == 1 and record.conditions == 0) {",
            "            try testing.expectEqualSlices(",
            "                u21,",
            "                &.{ 'S', 'S' },",
            "                componentsFor(record, .upper),",
            "            );",
            "            found_upper = true;",
            "        }",
            "    }",
            "    try testing.expect(found_upper);",
            "    try testing.expectEqual(@as(usize, 0), recordsFor(0x0041).len);",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    input_path = Path(sys.argv[1])
    output_path = Path(sys.argv[2])
    records, components = parse_records(checked_text(input_path))
    output_path.write_text(render(records, components), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
