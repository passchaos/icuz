#!/usr/bin/env python3
"""Generate CLDR 48 cardinal plural rules and conformance samples.

Usage:
    generate_plurals.py plurals.json out_dir
"""

from __future__ import annotations

import hashlib
import json
import struct
import sys
from pathlib import Path

INPUT_SHA256 = "6c0a48e9bcfc25856f90202f703c2c7f89c105d6868f7712a943a6ed2dcbe8f4"
CATEGORIES = ("zero", "one", "two", "few", "many", "other")
CATEGORY_INDEX = {name: index for index, name in enumerate(CATEGORIES)}
MAX_SAMPLES_PER_CATEGORY = 200


def checked_text(path: Path) -> str:
    data = path.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != INPUT_SHA256:
        raise SystemExit(
            f"{path}: expected CLDR 48 SHA-256 {INPUT_SHA256}, "
            f"found {actual}"
        )
    return data.decode("utf-8")


def split_rule(value: str) -> tuple[str, str]:
    rule = value.split("@", 1)[0].strip()
    return rule, value


def parse_samples(value: str) -> tuple[list[str], list[str]]:
    integer_samples: list[str] = []
    decimal_samples: list[str] = []
    for section_name, target in (
        ("integer", integer_samples),
        ("decimal", decimal_samples),
    ):
        marker = "@" + section_name
        start = value.find(marker)
        if start < 0:
            continue
        start += len(marker)
        end = len(value)
        for other in ("@integer", "@decimal"):
            position = value.find(other, start)
            if position >= 0:
                end = min(end, position)
        for token in value[start:end].split(","):
            token = token.strip()
            if not token or "…" in token or "c" in token:
                continue
            if section_name == "integer":
                target.extend(expand_integer(token))
            else:
                target.extend(expand_decimal(token))
    return integer_samples, decimal_samples


def expand_integer(token: str) -> list[str]:
    if "~" in token:
        first, last = token.split("~", 1)
        start = int(first)
        end = int(last)
        if end < start:
            return []
        step = 1
        count = (end - start) // step + 1
        if count > 50:
            step = max(1, count // 50)
        return [str(value) for value in range(start, end + 1, step)]
    return [str(int(token))]


def expand_decimal(token: str) -> list[str]:
    if "~" in token:
        first, last = token.split("~", 1)
        precision = len(first.split(".", 1)[1]) if "." in first else 0
        scale = 10**precision
        start = round(float(first) * scale)
        end = round(float(last) * scale)
        if end < start:
            return []
        count = end - start + 1
        step = 1 if count <= 50 else max(1, count // 50)
        result: list[str] = []
        for value in range(start, end + 1, step):
            result.append(format_scaled(value, precision))
        return result
    return [token]


def format_scaled(value: int, precision: int) -> str:
    if precision == 0:
        return str(value)
    scale = 10**precision
    whole = value // scale
    fraction = value % scale
    return f"{whole}.{fraction:0{precision}d}"


def render_rules(
    rules: dict[str, dict[str, str]],
    *,
    generator: str = "tools/unicode/format/generate_plurals.py",
    source_name: str = "plurals.json",
    source_sha: str = INPUT_SHA256,
) -> str:
    lines = [
        f"// Generated by {generator} from CLDR 48.",
        f"// {source_name} SHA-256: {source_sha}",
        "",
        "pub const Rule = struct {",
        "    locale: []const u8,",
        '    zero: []const u8 = "",',
        '    one: []const u8 = "",',
        '    two: []const u8 = "",',
        '    few: []const u8 = "",',
        '    many: []const u8 = "",',
        "};",
        "",
        "pub const rules = [_]Rule{",
    ]
    for locale in sorted(rules):
        values = rules[locale]
        fields = ", ".join(
            f'.{category} = "{values.get(category, "")}"'
            for category in CATEGORIES
            if category != "other"
        )
        lines.append(f'    .{{ .locale = "{locale}", {fields} }},')
    lines.extend(["};", ""])
    return "\n".join(lines)


def build_cases(
    rules: dict[str, dict[str, str]],
    annotations: dict[str, dict[str, tuple[str, str]]],
) -> list[tuple[str, int, int, str]]:
    cases: list[tuple[str, int, int, str]] = []
    for locale in sorted(rules):
        for category in CATEGORIES:
            rule, annotation = annotations[locale].get(category, ("", ""))
            integer_samples, decimal_samples = parse_samples(annotation)
            for sample in integer_samples[:MAX_SAMPLES_PER_CATEGORY]:
                cases.append((locale, CATEGORY_INDEX[category], 0, sample))
            for sample in decimal_samples[:MAX_SAMPLES_PER_CATEGORY]:
                cases.append((locale, CATEGORY_INDEX[category], 1, sample))
    return cases


def render_conformance(cases: list[tuple[str, int, int, str]]) -> bytes:
    payload = bytearray(
        struct.pack("<4sBBBB I", b"CJPL", 1, 48, 0, 0, len(cases))
    )
    for locale, category, kind, text in cases:
        locale_bytes = locale.encode("utf-8")
        text_bytes = text.encode("utf-8")
        if len(locale_bytes) > 0xFF or len(text_bytes) > 0xFFFF:
            raise SystemExit("plural conformance string too long")
        payload += struct.pack(
            "<BBBH",
            len(locale_bytes),
            category,
            kind,
            len(text_bytes),
        )
        payload += locale_bytes
        payload += text_bytes
    return bytes(payload)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    input_path = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)

    document = json.loads(checked_text(input_path))
    cardinal = document["supplemental"]["plurals-type-cardinal"]

    rules: dict[str, dict[str, str]] = {}
    annotations: dict[str, dict[str, tuple[str, str]]] = {}
    for locale, categories in cardinal.items():
        rules[locale] = {}
        annotations[locale] = {}
        for key, value in categories.items():
            category = key.removeprefix("pluralRule-count-")
            if category not in CATEGORY_INDEX:
                continue
            rule, annotation = split_rule(value)
            rules[locale][category] = rule
            annotations[locale][category] = (rule, annotation)

    (out_dir / "plurals_data.zig").write_text(
        render_rules(rules),
        encoding="utf-8",
    )
    (out_dir / "plurals_conformance.bin").write_bytes(
        render_conformance(build_cases(rules, annotations))
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
