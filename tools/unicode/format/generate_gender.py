#!/usr/bin/env python3
"""Generate CLDR list-gender rules.

Usage:
    generate_gender.py cldr-common-48.zip out_dir

Reads `common/supplemental/genderList.xml` and emits `gender_data.zig` with
the list-gender rule for each locale.
"""

from __future__ import annotations

import hashlib
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

CLDR_SHA256 = "06c7c698d6fd8d67cefac15a0206b0109b00e0ef1636f86f84449fa959561f74"
CLDR_VERSION = 48

RULES = {
    "neutral": "neutral",
    "mixedNeutral": "mixed_neutral",
    "maleTaints": "male_taints",
}


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    archive_path = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    data = archive_path.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != CLDR_SHA256:
        raise SystemExit(
            f"{archive_path}: expected CLDR {CLDR_VERSION} SHA-256 "
            f"{CLDR_SHA256}, found {actual}"
        )

    rules: dict[str, str] = {}
    with zipfile.ZipFile(archive_path) as archive:
        root = ET.fromstring(
            archive.read("common/supplemental/genderList.xml")
        )
        for element in root.iter("personList"):
            rule = RULES.get(element.get("type", ""))
            if rule is None:
                continue
            for locale in element.get("locales", "").split():
                rules.setdefault(locale, rule)

    lines = [
        f"// Generated by tools/unicode/format/generate_gender.py from CLDR {CLDR_VERSION}.",
        f"// cldr-common-48.zip SHA-256: {CLDR_SHA256}",
        "",
        "pub const Rule = enum { neutral, mixed_neutral, male_taints };",
        "",
        "pub const Locale = struct {",
        "    id: []const u8,",
        "    rule: Rule,",
        "};",
        "",
        "/// Sorted by locale.",
        "pub const locales = [_]Locale{",
    ]
    for locale in sorted(rules):
        lines.append(f'    .{{ .id = "{locale}", .rule = .{rules[locale]} }},')
    lines.append("};")
    lines.append("")

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "gender_data.zig").write_text("\n".join(lines))
    print(f"wrote {out_dir / 'gender_data.zig'}: {len(rules)} locales")


if __name__ == "__main__":
    main()
