#!/usr/bin/env python3
"""Generate the CLDR numbering system table.

Usage:
    generate_numbering_systems.py cldr-common-48.zip out_dir

Reads `common/supplemental/numberingSystems.xml` for numeric systems and
`common/main/root.xml` for per-system symbols, then emits
`numbering_systems.zig`.
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path


LOCALES = (
    "af", "am", "ar", "az", "be", "bg", "bn", "bs", "ca", "cs",
    "cy", "da", "de", "de-AT", "de-CH", "el", "en", "en-AU", "en-CA",
    "en-GB", "en-IN", "es", "es-419", "es-MX", "et", "eu", "fa", "fi",
    "fil", "fr", "fr-CA", "ga", "gl", "gu", "he", "hi", "hr", "hu",
    "hy", "id", "is", "it", "ja", "ka", "kk", "km", "kn", "ko", "lo",
    "lt", "lv", "mk", "ml", "mn", "mr", "ms", "mt", "my", "nb", "ne",
    "nl", "nl-BE", "pa", "pl", "ps", "pt", "pt-PT", "ro", "ru", "si",
    "sk", "sl", "sq", "sr", "sv", "sw", "ta", "te", "th", "tr", "uk",
    "ur", "uz", "vi", "zh", "zh-Hant", "zu",
)

PARENT = {
    "de-AT": "de", "de-CH": "de", "en-AU": "en-001", "en-CA": "en-001",
    "en-GB": "en-001", "en-IN": "en-001", "es-419": "es", "es-MX": "es-419",
    "fr-CA": "fr", "nb": "no", "nl-BE": "nl", "pt-PT": "pt", "zh-Hant": "root",
}


def zig_string(value: str) -> str:
    result = '"'
    for byte in value.encode("utf-8"):
        if byte == 0x22:
            result += '\\"'
        elif byte == 0x5C:
            result += "\\\\"
        elif 0x20 <= byte < 0x7F:
            result += chr(byte)
        else:
            result += f"\\x{byte:02x}"
    result += '"'
    return result


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    archive_path = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(archive_path) as archive:
        systems_doc = ET.fromstring(
            archive.read("common/supplemental/numberingSystems.xml")
        )
        root_doc = ET.fromstring(archive.read("common/main/root.xml"))

    symbols = {}
    numbers = root_doc.find(".//numbers")
    if numbers is not None:
        for block in numbers.findall("symbols"):
            name = block.get("numberSystem")
            if not name:
                continue
            symbols[name] = {
                "decimal": block.findtext("decimal") or "",
                "group": block.findtext("group") or "",
                "minus": block.findtext("minusSign") or "",
                "plus": block.findtext("plusSign") or "",
            }

    entries = []
    for system in systems_doc.findall(".//numberingSystem"):
        if system.get("type") != "numeric":
            continue
        identifier = system.get("id")
        digits = system.get("digits")
        if not identifier or not digits or len(digits) != 10:
            continue
        entry_symbols = symbols.get(identifier, {})
        entries.append(
            (
                identifier,
                digits,
                entry_symbols.get("decimal", ""),
                entry_symbols.get("group", ""),
                entry_symbols.get("minus", ""),
                entry_symbols.get("plus", ""),
            )
        )
    entries.sort(key=lambda item: item[0])

    lines = [
        "// Generated by tools/unicode/format/generate_numbering_systems.py from CLDR 48.",
        "",
        "const std = @import(\"std\");",
        "",
        "pub const System = struct {",
        "    id: []const u8,",
        "    digits: [10]u21,",
        "    decimal: []const u8,",
        "    group: []const u8,",
        "    minus: []const u8,",
        "    plus: []const u8,",
        "};",
        "",
        "pub const systems = [_]System{",
    ]
    for identifier, digits, decimal, group, minus, plus in entries:
        digit_values = ", ".join(f"0x{ord(character):x}" for character in digits)
        lines.append(
            "    .{ "
            f".id = {zig_string(identifier)}, "
            f".digits = .{{ {digit_values} }}, "
            f".decimal = {zig_string(decimal)}, "
            f".group = {zig_string(group)}, "
            f".minus = {zig_string(minus)}, "
            f".plus = {zig_string(plus)} "
            "},"
        )
    lines.append("};")
    lines.append("")
    lines.append("pub fn find(name: []const u8) ?System {")
    lines.append("    var low: usize = 0;")
    lines.append("    var high: usize = systems.len;")
    lines.append("    while (low < high) {")
    lines.append("        const middle = low + (high - low) / 2;")
    lines.append("        switch (@import(\"std\").mem.order(u8, systems[middle].id, name)) {")
    lines.append("            .lt => low = middle + 1,")
    lines.append("            .gt => high = middle,")
    lines.append("            .eq => return systems[middle],")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return null;")
    lines.append("}")
    lines.append("")

    # Locale-specific symbol overrides for non-default numbering systems.
    locale_symbols = []
    with zipfile.ZipFile(archive_path) as archive:
        for locale in LOCALES:
            chain: list[str] = []
            current = locale
            seen: set[str] = set()
            while current not in seen:
                seen.add(current)
                chain.append(current)
                if current == "root":
                    break
                parent = PARENT.get(current)
                if parent is None:
                    parent = current.split("-")[0]
                if parent == current:
                    parent = "root"
                current = parent
            merged: dict[str, dict[str, str]] = {}
            for name in chain:
                if name == "root":
                    continue
                filename = name.replace("-", "_")
                try:
                    text = archive.read(f"common/main/{filename}.xml")
                except KeyError:
                    continue
                document = ET.fromstring(text)
                numbers = document.find(".//numbers")
                if numbers is None:
                    continue
                for block in numbers.findall("symbols"):
                    system = block.get("numberSystem")
                    if not system:
                        continue
                    entry = merged.setdefault(system, {})
                    for field, tag in (
                        ("decimal", "decimal"),
                        ("group", "group"),
                        ("minus", "minusSign"),
                        ("plus", "plusSign"),
                    ):
                        if field in entry:
                            continue
                        value = block.findtext(tag)
                        if value is not None and value != "":
                            entry[field] = value
            for system, entry in merged.items():
                if any(entry.values()):
                    locale_symbols.append(
                        (
                            locale,
                            system,
                            entry.get("decimal", ""),
                            entry.get("group", ""),
                            entry.get("minus", ""),
                            entry.get("plus", ""),
                        )
                    )
    locale_symbols.sort(key=lambda item: (item[0], item[1]))

    lines.append("pub const Override = struct {")
    lines.append("    locale: []const u8,")
    lines.append("    system: []const u8,")
    lines.append("    decimal: []const u8,")
    lines.append("    group: []const u8,")
    lines.append("    minus: []const u8,")
    lines.append("    plus: []const u8,")
    lines.append("};")
    lines.append("")
    lines.append("pub const overrides = [_]Override{")
    for locale, system, decimal, group, minus, plus in locale_symbols:
        lines.append(
            "    .{ "
            f".locale = {zig_string(locale)}, "
            f".system = {zig_string(system)}, "
            f".decimal = {zig_string(decimal)}, "
            f".group = {zig_string(group)}, "
            f".minus = {zig_string(minus)}, "
            f".plus = {zig_string(plus)} "
            "},"
        )
    lines.append("};")
    lines.append("")
    lines.append("pub fn findOverride(locale: []const u8, system: []const u8) ?Override {")
    lines.append("    var low: usize = 0;")
    lines.append("    var high: usize = overrides.len;")
    lines.append("    while (low < high) {")
    lines.append("        const middle = low + (high - low) / 2;")
    lines.append("        const entry = overrides[middle];")
    lines.append("        const order = std.mem.order(u8, entry.locale, locale);")
    lines.append("        if (order == .lt or (order == .eq and std.mem.order(u8, entry.system, system) == .lt)) {")
    lines.append("            low = middle + 1;")
    lines.append("        } else if (order == .gt or std.mem.order(u8, entry.system, system) == .gt) {")
    lines.append("            high = middle;")
    lines.append("        } else {")
    lines.append("            return entry;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return null;")
    lines.append("}")
    lines.append("")
    (out_dir / "numbering_systems.zig").write_text(
        "\n".join(lines), encoding="utf-8"
    )
    print(f"generated {len(entries)} numbering systems", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
