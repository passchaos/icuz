#!/usr/bin/env python3
"""Generate CLDR weekend start/end data.

Usage:
    generate_weekend.py cldr-common-48.zip out_dir

Reads `common/supplemental/supplementalData.xml` and emits
`weekend_data.zig` with per-region weekend start and end weekdays.
"""

from __future__ import annotations

import hashlib
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

CLDR_SHA256 = "06c7c698d6fd8d67cefac15a0206b0109b00e0ef1636f86f84449fa959561f74"
CLDR_VERSION = 48

DAYS = {
    "sun": 0,
    "mon": 1,
    "tue": 2,
    "wed": 3,
    "thu": 4,
    "fri": 5,
    "sat": 6,
}


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    archive = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    data = archive.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != CLDR_SHA256:
        raise SystemExit(
            f"{archive}: expected CLDR {CLDR_VERSION} SHA-256 "
            f"{CLDR_SHA256}, found {actual}"
        )
    with zipfile.ZipFile(archive) as zf:
        root = ET.fromstring(
            zf.read("common/supplemental/supplementalData.xml")
        )

    starts: dict[str, int] = {}
    ends: dict[str, int] = {}
    default_start = 6
    default_end = 0
    for element in root.iter("weekendStart"):
        day = DAYS[element.get("day")]
        for territory in element.get("territories", "").split():
            if territory == "001":
                default_start = day
                continue
            starts.setdefault(territory, day)
    for element in root.iter("weekendEnd"):
        day = DAYS[element.get("day")]
        for territory in element.get("territories", "").split():
            if territory == "001":
                default_end = day
                continue
            ends.setdefault(territory, day)

    regions = sorted(set(starts) | set(ends))
    lines = [
        f"// Generated by tools/unicode/format/generate_weekend.py from CLDR {CLDR_VERSION}.",
        f"// cldr-common-48.zip SHA-256: {CLDR_SHA256}",
        "",
        "pub const Region = struct {",
        "    id: []const u8,",
        "    start: u8,",
        "    end: u8,",
        "};",
        "",
        f"pub const default_start: u8 = {default_start};",
        f"pub const default_end: u8 = {default_end};",
        "",
        "/// Sorted by region code.",
        "pub const regions = [_]Region{",
    ]
    for region in regions:
        start = starts.get(region, default_start)
        end = ends.get(region, default_end)
        lines.append(
            f'    .{{ .id = "{region}", .start = {start}, .end = {end} }},'
        )
    lines.append("};")
    lines.append("")

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "weekend_data.zig").write_text("\n".join(lines))
    print(
        f"wrote {out_dir / 'weekend_data.zig'}: {len(regions)} regions, "
        f"default {default_start}-{default_end}"
    )


if __name__ == "__main__":
    main()
