#!/usr/bin/env python3
"""Generate CLDR plural range data.

Usage:
    generate_plural_ranges.py cldr-common-48.zip out_dir

Reads `common/supplemental/pluralRanges.xml` and emits
`plural_ranges_data.zig` with one 6x6 result table per locale.
"""

from __future__ import annotations

import hashlib
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

CLDR_SHA256 = "06c7c698d6fd8d67cefac15a0206b0109b00e0ef1636f86f84449fa959561f74"
CLDR_VERSION = 48

CATEGORIES = ("zero", "one", "two", "few", "many", "other")


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    archive = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    data = archive.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != CLDR_SHA256:
        raise SystemExit(
            f"{archive}: expected CLDR {CLDR_VERSION} SHA-256 "
            f"{CLDR_SHA256}, found {actual}"
        )
    with zipfile.ZipFile(archive) as zf:
        root = ET.fromstring(
            zf.read("common/supplemental/pluralRanges.xml")
        )

    tables: dict[str, list[int]] = {}
    for ranges in root.iter("pluralRanges"):
        locales = ranges.get("locales", "").split()
        if not locales:
            continue
        table = [CATEGORIES.index("other")] * 36
        for rule in ranges.findall("pluralRange"):
            start = CATEGORIES.index(rule.get("start"))
            end = CATEGORIES.index(rule.get("end"))
            table[start * 6 + end] = CATEGORIES.index(rule.get("result"))
        for locale in locales:
            tables[locale] = table

    lines = [
        f"// Generated by tools/unicode/format/generate_plural_ranges.py from CLDR {CLDR_VERSION}.",
        f"// cldr-common-48.zip SHA-256: {CLDR_SHA256}",
        "",
        "pub const Locale = struct {",
        "    id: []const u8,",
        "    /// Result categories indexed by start * 6 + end.",
        "    results: [36]u8,",
        "};",
        "",
        "/// Sorted by locale.",
        "pub const locales = [_]Locale{",
    ]
    for locale in sorted(tables):
        values = ", ".join(str(value) for value in tables[locale])
        lines.append(
            f'    .{{ .id = "{locale}", .results = .{{ {values} }} }},'
        )
    lines.append("};")
    lines.append("")

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "plural_ranges_data.zig").write_text("\n".join(lines))
    print(
        f"wrote {out_dir / 'plural_ranges_data.zig'}: {len(tables)} locales"
    )


if __name__ == "__main__":
    main()
