#!/usr/bin/env python3
"""Generate CLDR calendar preference data.

Usage:
    generate_calendar_preferences.py cldr-common-48.zip \
        src/unicode/format/calendar_preferences_data.zig

The table maps a territory to CLDR's ordered calendar preference list from
`supplementalData.xml` (`calendarPreferenceData`).
"""

from __future__ import annotations

import hashlib
import re
import sys
import zipfile
from pathlib import Path
import xml.etree.ElementTree as ET

CLDR_SHA256 = "06c7c698d6fd8d67cefac15a0206b0109b00e0ef1636f86f84449fa959561f74"
CLDR_VERSION = 48


def checked_zip(path: Path) -> zipfile.ZipFile:
    actual = hashlib.sha256(path.read_bytes()).hexdigest()
    if actual != CLDR_SHA256:
        raise SystemExit(
            f"{path}: expected CLDR {CLDR_VERSION} SHA-256 {CLDR_SHA256}, "
            f"found {actual}"
        )
    return zipfile.ZipFile(path)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    archive = checked_zip(Path(sys.argv[1]))
    text = archive.read("common/supplemental/supplementalData.xml").decode("utf-8")
    root = ET.fromstring(text)
    preferences: dict[str, list[str]] = {}
    for entry in root.findall(".//calendarPreferenceData/calendarPreference"):
        ordering = entry.get("ordering", "")
        calendars = ordering.split()
        for region in entry.get("territories", "").split():
            preferences[region] = calendars

    output = [
        f"// Generated by tools/unicode/format/generate_calendar_preferences.py from CLDR {CLDR_VERSION}.",
        "// Source: common/supplemental/supplementalData.xml (calendarPreferenceData).",
        "",
        "pub const Preference = struct {",
        "    region: []const u8,",
        "    calendars: []const []const u8,",
        "};",
        "",
        "pub const preferences = [_]Preference{",
    ]
    for region in sorted(preferences):
        calendars = ", ".join(f'"{name}"' for name in preferences[region])
        output.append(
            f'    .{{ .region = "{region}", .calendars = &.{{ {calendars} }} }},'
        )
    output.append("};")
    Path(sys.argv[2]).write_text("\n".join(output) + "\n")
    print(f"wrote {len(preferences)} territory preferences")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
