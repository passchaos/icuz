#!/usr/bin/env python3
"""Generate CLDR week data (first day and minimal days) per region.

Usage:
    generate_week.py cldr-common-48.zip out_dir

Reads `common/supplemental/supplementalData.xml` and emits `week_data.zig`
with per-region first-day and minimal-days-in-first-week values.
"""

from __future__ import annotations

import hashlib
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

CLDR_SHA256 = "06c7c698d6fd8d67cefac15a0206b0109b00e0ef1636f86f84449fa959561f74"
CLDR_VERSION = 48

DAYS = {
    "sun": 0,
    "mon": 1,
    "tue": 2,
    "wed": 3,
    "thu": 4,
    "fri": 5,
    "sat": 6,
}


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    archive = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    data = archive.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != CLDR_SHA256:
        raise SystemExit(
            f"{archive}: expected CLDR {CLDR_VERSION} SHA-256 "
            f"{CLDR_SHA256}, found {actual}"
        )
    with zipfile.ZipFile(archive) as zf:
        root = ET.fromstring(
            zf.read("common/supplemental/supplementalData.xml")
        )

    first_days: dict[str, int] = {}
    min_days: dict[str, int] = {}
    default_first_day = 1
    default_min_days = 1
    for element in root.iter("firstDay"):
        if element.get("alt") is not None:
            continue
        day = DAYS.get(element.get("day", ""))
        if day is None:
            continue
        for territory in element.get("territories", "").split():
            if territory == "001":
                default_first_day = day
                continue
            first_days.setdefault(territory, day)
    for element in root.iter("minDays"):
        if element.get("alt") is not None:
            continue
        try:
            count = int(element.get("count", ""))
        except ValueError:
            continue
        for territory in element.get("territories", "").split():
            if territory == "001":
                default_min_days = count
                continue
            min_days.setdefault(territory, count)

    regions = sorted(set(first_days) | set(min_days))
    lines = [
        f"// Generated by tools/unicode/format/generate_week.py from CLDR {CLDR_VERSION}.",
        f"// cldr-common-48.zip SHA-256: {CLDR_SHA256}",
        "",
        "pub const Region = struct {",
        "    id: []const u8,",
        "    /// First day of the week (Sunday = 0).",
        "    first_day: u8,",
        "    /// Minimum days in the first week of the year.",
        "    minimal_days: u8,",
        "};",
        "",
        f"pub const default_first_day: u8 = {default_first_day};",
        f"pub const default_minimal_days: u8 = {default_min_days};",
        "",
        "/// Sorted by region code.",
        "pub const regions = [_]Region{",
    ]
    for region in regions:
        first = first_days.get(region, default_first_day)
        minimum = min_days.get(region, default_min_days)
        lines.append(
            f'    .{{ .id = "{region}", .first_day = {first}, '
            f".minimal_days = {minimum} }},"
        )
    lines.append("};")
    lines.append("")

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "week_data.zig").write_text("\n".join(lines))
    print(
        f"wrote {out_dir / 'week_data.zig'}: {len(regions)} regions, "
        f"default first day {default_first_day}, min days {default_min_days}"
    )


if __name__ == "__main__":
    main()
