#!/usr/bin/env python3
"""Generate the CLDR Windows time zone ID mapping.

Usage:
    generate_windows.py cldr-common-48.zip out_dir

Reads `common/supplemental/windowsZones.xml` and emits a `windows_data.zig`
table with the Windows-to-IANA and IANA-to-Windows mappings used by
src/unicode/timezone/windows.zig.
"""

from __future__ import annotations

import hashlib
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

CLDR_SHA256 = "06c7c698d6fd8d67cefac15a0206b0109b00e0ef1636f86f84449fa959561f74"
CLDR_VERSION = 48


def zig_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    archive = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    data = archive.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != CLDR_SHA256:
        raise SystemExit(
            f"{archive}: expected CLDR {CLDR_VERSION} SHA-256 "
            f"{CLDR_SHA256}, found {actual}"
        )
    with zipfile.ZipFile(archive) as zf:
        xml = zf.read("common/supplemental/windowsZones.xml")

    root = ET.fromstring(xml)
    mappings: list[tuple[str, str, str]] = []
    for zone in root.iter("mapZone"):
        windows_id = zone.get("other")
        region = zone.get("territory")
        types = zone.get("type")
        if windows_id is None or region is None or types is None:
            raise SystemExit("mapZone is missing attributes")
        for iana in types.split():
            mappings.append((windows_id, region, iana))

    windows_ids = sorted({windows for windows, _, _ in mappings})
    zones = sorted({iana for _, _, iana in mappings})
    windows_index = {value: index for index, value in enumerate(windows_ids)}
    zone_index = {value: index for index, value in enumerate(zones)}

    # Windows ID lookup is by (Windows ID, region). A CLDR region can list
    # several IANA zones; ICU uses the first one, so keep first occurrences
    # in document order. Reverse lookup is by IANA zone; the CLDR data maps
    # every IANA zone to exactly one Windows ID, and the "001" entry is
    # preferred when a zone has several regional entries.
    forward: dict[tuple[str, str], str] = {}
    for windows, region, iana in mappings:
        forward.setdefault((windows, region), iana)
    by_windows = sorted(
        (windows_index[windows], region, zone_index[iana])
        for (windows, region), iana in forward.items()
    )
    by_zone = sorted(
        (zone_index[iana], 0 if region == "001" else 1, windows_index[windows])
        for windows, region, iana in mappings
    )

    lines = [
        f"// Generated by tools/unicode/timezone/generate_windows.py from CLDR {CLDR_VERSION}.",
        f"// cldr-common-48.zip SHA-256: {CLDR_SHA256}",
        "",
        "pub const Entry = struct {",
        "    windows: u16,",
        "    region: []const u8,",
        "    zone: u16,",
        "};",
        "",
        "pub const ZoneEntry = struct {",
        "    zone: u16,",
        "    preferred: bool,",
        "    windows: u16,",
        "};",
        "",
        "pub const windows_ids = [_][]const u8{",
    ]
    for value in windows_ids:
        lines.append(f"    {zig_string(value)},")
    lines.append("};")
    lines.append("")
    lines.append("pub const zones = [_][]const u8{")
    for value in zones:
        lines.append(f"    {zig_string(value)},")
    lines.append("};")
    lines.append("")
    lines.append("/// Sorted by Windows ID, then region.")
    lines.append("pub const by_windows = [_]Entry{")
    for windows, region, zone in by_windows:
        lines.append(
            "    .{ .windows = %d, .region = %s, .zone = %d },"
            % (windows, zig_string(region), zone)
        )
    lines.append("};")
    lines.append("")
    lines.append("/// Sorted by IANA zone, with the region 001 entry first.")
    lines.append("pub const by_zone = [_]ZoneEntry{")
    for zone, preferred, windows in by_zone:
        lines.append(
            "    .{ .zone = %d, .preferred = %s, .windows = %d },"
            % (zone, "true" if preferred == 0 else "false", windows)
        )
    lines.append("};")
    lines.append("")

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "windows_data.zig").write_text("\n".join(lines))
    print(
        f"wrote {out_dir / 'windows_data.zig'}: "
        f"{len(windows_ids)} Windows IDs, {len(zones)} zones, "
        f"{len(by_windows)} mappings"
    )


if __name__ == "__main__":
    main()
