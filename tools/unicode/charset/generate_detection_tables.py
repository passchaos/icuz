#!/usr/bin/env python3
"""Generate charset-detection tables from ICU's recognizer sources.

Usage:
    generate_detection_tables.py csrsbcs.cpp csrmbcs.cpp OUT

The SBCS char maps/ngram lists and MBCS common-character lists are copied
from ICU's charset recognizers so icuz's detector produces the same
confidences. Source files are from ICU's `icu4c/source/i18n/` directory.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path


def parse_simple_arrays(text: str, source: Path) -> dict[str, tuple[str, list[int]]]:
    result: dict[str, tuple[str, list[int]]] = {}
    pattern = re.compile(
        r"static const (uint8_t|uint16_t|int32_t)\s+(\w+)\s*\[\s*\]\s*=\s*\{(.*?)\}\s*;",
        re.S,
    )
    for match in pattern.finditer(text):
        type_name, name, body = match.groups()
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        body = re.sub(r"//.*", "", body)
        values = [int(token.strip(), 0) for token in body.split(",") if token.strip()]
        if not values:
            raise SystemExit(f"{source}: empty array {name}")
        result[name] = (type_name, values)
    return result


def parse_ngram_languages(
    text: str,
    name: str,
    source: Path,
) -> list[tuple[list[int], str]]:
    match = re.search(
        r"static const NGramsPlusLang\s+" + name + r"\s*\[\s*\]\s*=\s*\{(.*?)\n\};",
        text,
        re.S,
    )
    if match is None:
        return []
    body = match.group(1)
    entries = []
    entry_pattern = re.compile(
        r"\{\s*\{(.*?)\}\s*,\s*\"([A-Za-z]+)\"\s*\}",
        re.S,
    )
    for entry in entry_pattern.finditer(body):
        values = [
            int(token.strip(), 0)
            for token in entry.group(1).split(",")
            if token.strip()
        ]
        if len(values) != 64:
            raise SystemExit(f"{source}: {name} entry has {len(values)} ngrams")
        entries.append((values, entry.group(2)))
    return entries


def zig_array(name: str, type_name: str, values: list[int], width: int = 12) -> list[str]:
    lines = [f"pub const {name} = [_]{type_name}{{"]
    for index in range(0, len(values), width):
        chunk = ", ".join(str(value) for value in values[index : index + width])
        lines.append(f"    {chunk},")
    lines.append("};")
    return lines


def zig_language_ngrams(
    name: str,
    entries: list[tuple[list[int], str]],
) -> list[str]:
    lines = [f"pub const {name} = [_]LanguageNgrams{{"]
    for values, language in entries:
        lines.append(f'    .{{ .language = "{language}", .ngrams = &.{{')
        for index in range(0, len(values), 12):
            chunk = ", ".join(str(value) for value in values[index : index + 12])
            lines.append(f"        {chunk},")
        lines.append("    } },")
    lines.append("};")
    return lines


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    sbcs_path = Path(sys.argv[1])
    mbcs_path = Path(sys.argv[2])
    output_path = Path(sys.argv[3])
    sbcs = sbcs_path.read_text(encoding="utf-8")
    mbcs = mbcs_path.read_text(encoding="utf-8")
    simple = parse_simple_arrays(sbcs, sbcs_path)
    simple.update(parse_simple_arrays(mbcs, mbcs_path))

    output: list[str] = [
        "// Generated by tools/unicode/charset/generate_detection_tables.py.",
        "// Source: ICU csrsbcs.cpp and csrmbcs.cpp recognizer tables.",
        "",
        "pub const LanguageNgrams = struct {",
        "    language: []const u8,",
        "    ngrams: []const i32,",
        "};",
        "",
    ]
    for name in sorted(simple):
        type_name, values = simple[name]
        zig_type = {"uint8_t": "u8", "uint16_t": "u16", "int32_t": "i32"}[type_name]
        output.extend(zig_array(name, zig_type, values))
        output.append("")
    for name in ("ngrams_8859_1", "ngrams_8859_2"):
        entries = parse_ngram_languages(sbcs, name, sbcs_path)
        output.extend(zig_language_ngrams(name, entries))
        output.append("")
    output_path.write_text("\n".join(output) + "\n")
    print(f"wrote {len(simple)} arrays and 2 language ngram tables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
