#!/usr/bin/env python3
"""Generate ISO 639-2 language and ISO 3166 country alpha-3 tables.

Usage:
    generate_iso3.py uloc.cpp out.zig

Parses the LANGUAGES/LANGUAGES_3 and COUNTRIES/COUNTRIES_3 arrays from ICU's
`uloc.cpp`.
"""

from __future__ import annotations

import hashlib
import re
import sys


def array_strings(source: str, name: str) -> list[str]:
    match = re.search(rf"constexpr const char\* {name}\[\]\s*=\s*\{{(.*?)\}};", source, re.S)
    if match is None:
        raise SystemExit(f"could not find {name}")
    body = match.group(1)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    return re.findall(r'"([^"\\]*)"', body)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    source = open(sys.argv[1], "r", encoding="utf-8").read()
    languages = array_strings(source, "LANGUAGES")
    languages_3 = array_strings(source, "LANGUAGES_3")
    countries = array_strings(source, "COUNTRIES")
    countries_3 = array_strings(source, "COUNTRIES_3")
    if len(languages) != len(languages_3):
        raise SystemExit("language table length mismatch")
    if len(countries) != len(countries_3):
        raise SystemExit("country table length mismatch")

    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    out = []
    out.append("// Generated by tools/unicode/locale/generate_iso3.py from ICU 78.3 uloc.cpp.")
    out.append("//! ISO 639-2 language and ISO 3166 country alpha-3 tables.")
    out.append(f"//! Source SHA-256: {digest}")
    out.append("")
    out.append("pub const Entry = struct {")
    out.append("    code: []const u8,")
    out.append("    alpha3: []const u8,")
    out.append("};")
    out.append("")
    out.append("pub const languages = [_]Entry{")
    for code, alpha3 in zip(languages, languages_3):
        out.append(f'    .{{ .code = "{code}", .alpha3 = "{alpha3}" }},')
    out.append("};")
    out.append("")
    out.append("pub const countries = [_]Entry{")
    for code, alpha3 in zip(countries, countries_3):
        out.append(f'    .{{ .code = "{code}", .alpha3 = "{alpha3}" }},')
    out.append("};")
    out.append("")
    with open(sys.argv[2], "w", encoding="utf-8") as file:
        file.write("\n".join(out))
    print(f"wrote {len(languages)} languages and {len(countries)} countries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
