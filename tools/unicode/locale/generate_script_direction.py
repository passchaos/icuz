#!/usr/bin/env python3
"""Generate the CLDR right-to-left script list.

Usage:
    generate_script_direction.py cldr-common-48.zip out_dir

Reads `common/properties/scriptMetadata.txt` and emits `direction_data.zig`
with the ISO 15924 script codes whose RTL field is YES.
"""

from __future__ import annotations

import hashlib
import sys
import zipfile
from pathlib import Path

CLDR_SHA256 = "06c7c698d6fd8d67cefac15a0206b0109b00e0ef1636f86f84449fa959561f74"
CLDR_VERSION = 48


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    archive_path = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    data = archive_path.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != CLDR_SHA256:
        raise SystemExit(
            f"{archive_path}: expected CLDR {CLDR_VERSION} SHA-256 "
            f"{CLDR_SHA256}, found {actual}"
        )

    rtl: set[str] = set()
    with zipfile.ZipFile(archive_path) as archive:
        text = archive.read("common/properties/scriptMetadata.txt").decode("utf-8")
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        fields = [field.strip() for field in line.split(";")]
        if len(fields) <= 6:
            continue
        script = fields[0]
        if len(script) != 4:
            continue
        if fields[6].upper() == "YES":
            rtl.add(script)

    lines = [
        f"// Generated by tools/unicode/locale/generate_script_direction.py from CLDR {CLDR_VERSION}.",
        f"// cldr-common-48.zip SHA-256: {CLDR_SHA256}",
        "",
        "/// ISO 15924 script codes whose scripts are right-to-left, sorted.",
        "pub const rtl_scripts = [_][]const u8{",
    ]
    for script in sorted(rtl):
        lines.append(f'    "{script}",')
    lines.append("};")
    lines.append("")

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "direction_data.zig").write_text("\n".join(lines))
    print(f"wrote {out_dir / 'direction_data.zig'}: {len(rtl)} RTL scripts")


if __name__ == "__main__":
    main()
