#!/usr/bin/env python3
"""Generate CLDR language-matching data.

Usage:
    generate_matcher.py cldr-common-48.zip out_dir

Reads `common/supplemental/languageInfo.xml` for the languageMatch rules,
match variables, and paradigm locales, and `supplementalData.xml` for the
territory containment used to expand macroregion variables such as $americas.
Emits `matcher_data.zig` consumed by src/unicode/locale/matcher.zig.
"""

from __future__ import annotations

import hashlib
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

CLDR_SHA256 = "06c7c698d6fd8d67cefac15a0206b0109b00e0ef1636f86f84449fa959561f74"
CLDR_VERSION = 48


def zig_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def canonical_subtag(value: str, index: int) -> str:
    if value == "*" or value.startswith("$"):
        return value
    if index == 0:
        return value.lower()
    if index == 1:
        return value.title()
    return value.upper()


def split_pattern(pattern: str) -> list[str]:
    fields = [canonical_subtag(value, index) for index, value in enumerate(
        pattern.split("_")
    )]
    while len(fields) < 3:
        fields.append("")
    return fields[:3]


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    archive = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    data = archive.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != CLDR_SHA256:
        raise SystemExit(
            f"{archive}: expected CLDR {CLDR_VERSION} SHA-256 "
            f"{CLDR_SHA256}, found {actual}"
        )
    with zipfile.ZipFile(archive) as zf:
        language_info = ET.fromstring(
            zf.read("common/supplemental/languageInfo.xml")
        )
        supplemental = ET.fromstring(
            zf.read("common/supplemental/supplementalData.xml")
        )

    containment: dict[str, list[str]] = {}
    for group in supplemental.iter("group"):
        if group.get("status") is not None:
            continue
        containment.setdefault(group.get("type"), []).extend(
            group.get("contains", "").split()
        )

    def expand(token: str) -> set[str]:
        if token in containment:
            result: set[str] = set()
            for child in containment[token]:
                result.update(expand(child))
            return result
        return {token}

    matches = None
    for element in language_info.iter("languageMatches"):
        if element.get("type") == "written_new":
            matches = element
            break
    if matches is None:
        raise SystemExit("languageInfo.xml: missing written_new matches")

    paradigms: list[str] = []
    variables: dict[str, list[str]] = {}
    rules: list[tuple[str, str, int, bool]] = []
    for element in matches:
        if element.tag == "paradigmLocales":
            paradigms = element.get("locales", "").split()
        elif element.tag == "matchVariable":
            identifier = element.get("id")
            value = element.get("value")
            if not identifier or value is None:
                raise SystemExit("matchVariable is missing attributes")
            regions: set[str] = set()
            first = True
            for token in value.replace("+", " + ").replace("-", " - ").split():
                if token in ("+", "-"):
                    operator = token
                    continue
                if first:
                    regions = expand(token)
                    first = False
                    operator = "+"
                    continue
                if operator == "+":
                    regions |= expand(token)
                else:
                    regions -= expand(token)
            variables[identifier.removeprefix("$")] = sorted(regions)
        elif element.tag == "languageMatch":
            desired = element.get("desired")
            supported = element.get("supported")
            distance = element.get("distance")
            percent = element.get("percent")
            if percent is not None and distance is None:
                # CLDR 48 uses distance values; percent is the older form.
                distance = str(round((100 - int(percent)) * 80 / 100))
            if desired is None or supported is None or distance is None:
                raise SystemExit("languageMatch is missing attributes")
            rules.append(
                (
                    desired,
                    supported,
                    int(distance),
                    element.get("oneway") == "true",
                )
            )

    lines = [
        f"// Generated by tools/unicode/locale/generate_matcher.py from CLDR {CLDR_VERSION}.",
        f"// cldr-common-48.zip SHA-256: {CLDR_SHA256}",
        "",
        "pub const Rule = struct {",
        "    desired_language: []const u8,",
        "    desired_script: []const u8,",
        "    desired_region: []const u8,",
        "    supported_language: []const u8,",
        "    supported_script: []const u8,",
        "    supported_region: []const u8,",
        "    distance: u8,",
        "    one_way: bool,",
        "};",
        "",
        "pub const Variable = struct {",
        "    name: []const u8,",
        "    regions: []const []const u8,",
        "};",
        "",
        "pub const paradigm_locales = [_][]const u8{",
    ]
    for locale in paradigms:
        lines.append(f"    {zig_string(locale)},")
    lines.append("};")
    lines.append("")
    lines.append("pub const variables = [_]Variable{")
    for identifier in sorted(variables):
        lines.append("    .{ .name = %s, .regions = &.{" % zig_string(identifier))
        for region in variables[identifier]:
            lines.append(f"        {zig_string(region)},")
        lines.append("    } },")
    lines.append("};")
    lines.append("")
    lines.append("/// In CLDR order; the first matching rule at a level wins.")
    lines.append("pub const rules = [_]Rule{")
    for desired, supported, distance, one_way in rules:
        desired_fields = split_pattern(desired)
        supported_fields = split_pattern(supported)
        lines.append(
            "    .{ .desired_language = %s, .desired_script = %s, "
            ".desired_region = %s, .supported_language = %s, "
            ".supported_script = %s, .supported_region = %s, "
            ".distance = %d, .one_way = %s },"
            % (
                zig_string(desired_fields[0]),
                zig_string(desired_fields[1]),
                zig_string(desired_fields[2]),
                zig_string(supported_fields[0]),
                zig_string(supported_fields[1]),
                zig_string(supported_fields[2]),
                distance,
                "true" if one_way else "false",
            )
        )
    lines.append("};")
    lines.append("")

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "matcher_data.zig").write_text("\n".join(lines))
    print(
        f"wrote {out_dir / 'matcher_data.zig'}: {len(rules)} rules, "
        f"{len(variables)} variables, {len(paradigms)} paradigm locales"
    )


if __name__ == "__main__":
    main()
