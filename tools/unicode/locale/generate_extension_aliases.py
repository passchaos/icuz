#!/usr/bin/env python3
"""Generate CLDR BCP 47 extension type aliases.

Usage:
    generate_extension_aliases.py cldr-common-48.zip out_dir

Reads `common/bcp47/*.xml` and emits `extension_aliases.zig` with the
`-u-` extension type aliases (for example `islamicc` -> `islamic-civil`).
"""

from __future__ import annotations

import hashlib
import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

CLDR_SHA256 = "06c7c698d6fd8d67cefac15a0206b0109b00e0ef1636f86f84449fa959561f74"
CLDR_VERSION = 48


def zig_string(value: str) -> str:
    result = '"'
    for byte in value.encode("utf-8"):
        if byte == 0x22:
            result += '\\"'
        elif byte == 0x5C:
            result += "\\\\"
        elif 0x20 <= byte < 0x7F:
            result += chr(byte)
        else:
            result += f"\\x{byte:02x}"
    result += '"'
    return result


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    archive_path = Path(sys.argv[1])
    out_dir = Path(sys.argv[2])
    data = archive_path.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != CLDR_SHA256:
        raise SystemExit(
            f"{archive_path}: expected CLDR {CLDR_VERSION} SHA-256 "
            f"{CLDR_SHA256}, found {actual}"
        )

    aliases: dict[tuple[str, str], str] = {}
    with zipfile.ZipFile(archive_path) as archive:
        for name in sorted(archive.namelist()):
            if not name.startswith("common/bcp47/") or not name.endswith(".xml"):
                continue
            try:
                root = ET.fromstring(archive.read(name))
            except ET.ParseError:
                continue
            for key in root.iter("key"):
                key_name = key.get("name", "")
                if len(key_name) != 2:
                    continue
                for element in key.iter("type"):
                    type_name = element.get("name", "")
                    if not type_name:
                        continue
                    preferred = element.get("preferred")
                    alias = element.get("alias")
                    deprecated = element.get("deprecated") == "true"
                    if deprecated:
                        # Deprecated values map to their preferred replacement.
                        canonical = preferred or alias
                        if not canonical or canonical == type_name:
                            continue
                        aliases.setdefault(
                            (key_name.lower(), type_name.lower()),
                            canonical.lower(),
                        )
                    else:
                        # `alias` is the legacy value; `name` is canonical.
                        if not alias or alias == type_name:
                            continue
                        aliases.setdefault(
                            (key_name.lower(), alias.lower()),
                            type_name.lower(),
                        )

    entries = sorted(aliases.items())
    lines = [
        f"// Generated by tools/unicode/locale/generate_extension_aliases.py from CLDR {CLDR_VERSION}.",
        f"// cldr-common-48.zip SHA-256: {CLDR_SHA256}",
        "",
        "pub const Alias = struct {",
        "    key: []const u8,",
        "    alias: []const u8,",
        "    canonical: []const u8,",
        "};",
        "",
        "/// Sorted by (key, alias).",
        "pub const aliases = [_]Alias{",
    ]
    for (key, alias), canonical in entries:
        lines.append(
            f"    .{{ .key = {zig_string(key)}, .alias = {zig_string(alias)}, "
            f".canonical = {zig_string(canonical)} }},"
        )
    lines.append("};")
    lines.append("")

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "extension_aliases.zig").write_text("\n".join(lines))
    print(
        f"wrote {out_dir / 'extension_aliases.zig'}: {len(entries)} aliases"
    )


if __name__ == "__main__":
    main()
