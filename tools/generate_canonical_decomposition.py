#!/usr/bin/env python3
"""Generate canonical and compatibility Unicode decompositions.

Usage:
    tools/generate_canonical_decomposition.py \
        path/to/UnicodeData.txt \
        src/unicode/canonical/decomposition.zig

Canonical recursive expansion produces NFD components. Compatibility recursive
expansion additionally applies compatibility mappings and produces NFKD
components. Hangul decomposition is algorithmic and is intentionally absent
from these tables.
"""

from __future__ import annotations

import sys
from pathlib import Path


def parse(
    path: Path,
) -> tuple[
    dict[int, tuple[int, ...]],
    dict[int, tuple[int, ...]],
    dict[int, str],
]:
    canonical: dict[int, tuple[int, ...]] = {}
    compatibility: dict[int, tuple[int, ...]] = {}
    categories: dict[int, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        if len(fields) < 6:
            continue
        codepoint = int(fields[0], 16)
        categories[codepoint] = fields[2]
        mapping = fields[5]
        if not mapping:
            continue
        if mapping.startswith("<"):
            # Compatibility mapping: "<compat> 0020 0308".
            compatibility[codepoint] = tuple(
                int(token, 16) for token in mapping.split()[1:]
            )
        else:
            canonical[codepoint] = tuple(int(token, 16) for token in mapping.split())
    return canonical, compatibility, categories


def expand_all(
    direct: dict[int, tuple[int, ...]],
) -> dict[int, tuple[int, ...]]:
    memo: dict[int, tuple[int, ...]] = {}

    def expand(codepoint: int, stack: frozenset[int] = frozenset()) -> tuple[int, ...]:
        if codepoint in memo:
            return memo[codepoint]
        if codepoint in stack:
            raise ValueError(f"decomposition cycle at U+{codepoint:04X}")
        result: list[int] = []
        for component in direct.get(codepoint, (codepoint,)):
            if component in direct:
                result.extend(expand(component, stack | {codepoint}))
            else:
                result.append(component)
        memo[codepoint] = tuple(result)
        return memo[codepoint]

    return {
        codepoint: expanded
        for codepoint in sorted(direct)
        if (expanded := expand(codepoint))
    }


def table_source(
    name: str,
    entries: dict[int, tuple[int, ...]],
) -> tuple[list[str], int]:
    flat: list[int] = []
    records: list[tuple[int, int, int]] = []
    for codepoint, components in entries.items():
        records.append((codepoint, len(flat), len(components)))
        flat.extend(components)
    if any(length > 0xFF for _, _, length in records):
        raise ValueError(f"{name} decomposition length exceeds u8")

    lines = [
        f"const {name}_records = [_]Record{{",
    ]
    for codepoint, offset, length in records:
        lines.append(
            f"    .{{ .codepoint = 0x{codepoint:x}, .offset = {offset}, .len = {length} }},"
        )
    lines.extend(["};", "", f"const {name}_components = [_]u21{{"])
    for start in range(0, len(flat), 16):
        chunk = ", ".join(f"0x{value:x}" for value in flat[start : start + 16])
        lines.append(f"    {chunk},")
    lines.extend(["};", ""])
    return lines, len(flat)


def render(
    canonical_direct: dict[int, tuple[int, ...]],
    canonical_recursive: dict[int, tuple[int, ...]],
    compatibility_direct: dict[int, tuple[int, ...]],
    compatibility_recursive: dict[int, tuple[int, ...]],
    categories: dict[int, str],
) -> str:
    lines = [
        "// Generated by tools/generate_canonical_decomposition.py from Unicode 17.0.0.",
        "// Canonical and compatibility mappings are recursively expanded.",
        "const Record = struct {",
        "    codepoint: u21,",
        "    offset: u32,",
        "    len: u8,",
        "};",
        "",
    ]
    mark_leading_entries = {
        codepoint: components
        for codepoint, components in canonical_recursive.items()
        if len(components) > 1 and
        categories.get(components[0], "").startswith("M")
    }
    for name, entries in (
        ("direct", canonical_direct),
        ("recursive", canonical_recursive),
        ("mark_leading", mark_leading_entries),
        ("compat_direct", compatibility_direct),
        ("compat_recursive", compatibility_recursive),
    ):
        table_lines, _ = table_source(name, entries)
        lines.extend(table_lines)
    lines.extend(
        [
            "fn lookup(codepoint: u21, records: []const Record, components: []const u21) ?[]const u21 {",
            "    var low: usize = 0;",
            "    var high: usize = records.len;",
            "    while (low < high) {",
            "        const mid = low + (high - low) / 2;",
            "        const record = records[mid];",
            "        if (codepoint < record.codepoint) {",
            "            high = mid;",
            "        } else if (codepoint > record.codepoint) {",
            "            low = mid + 1;",
            "        } else {",
            "            return components[record.offset .. record.offset + record.len];",
            "        }",
            "    }",
            "    return null;",
            "}",
            "",
            "/// Direct canonical decomposition (one step, no recursive expansion).",
            "pub fn directForCodepoint(codepoint: u21) ?[]const u21 {",
            "    return lookup(codepoint, &direct_records, &direct_components);",
            "}",
            "",
            "/// Recursively expanded canonical decomposition (NFD components).",
            "pub fn forCodepoint(codepoint: u21) ?[]const u21 {",
            "    return lookup(codepoint, &recursive_records, &recursive_components);",
            "}",
            "",
            "/// Canonical decomposition whose first component is a mark.",
            "pub fn markLeadingForCodepoint(codepoint: u21) ?[]const u21 {",
            "    return lookup(codepoint, &mark_leading_records, &mark_leading_components);",
            "}",
            "",
            "/// Direct compatibility or canonical decomposition (one step).",
            "pub fn compatibilityDirectForCodepoint(codepoint: u21) ?[]const u21 {",
            "    return lookup(codepoint, &compat_direct_records, &compat_direct_components);",
            "}",
            "",
            "/// Recursively expanded compatibility decomposition (NFKD components).",
            "pub fn compatibilityForCodepoint(codepoint: u21) ?[]const u21 {",
            "    return lookup(codepoint, &compat_recursive_records, &compat_recursive_components);",
            "}",
            "",
            'test "canonical and compatibility decompositions" {',
            '    const testing = @import("std").testing;',
            "    try testing.expectEqualSlices(u21, &.{ 0x0dd9, 0x0dca }, markLeadingForCodepoint(0x0dda).?);",
            "    try testing.expectEqualSlices(u21, &.{ 0x0041, 0x0302, 0x0301 }, forCodepoint(0x1ea4).?);",
            "    try testing.expectEqualSlices(u21, &.{ 0x00c2, 0x0301 }, directForCodepoint(0x1ea4).?);",
            "    try testing.expectEqualSlices(u21, &.{ 0x00c5 }, directForCodepoint(0x212b).?);",
            "    try testing.expectEqualSlices(u21, &.{ 0x0041, 0x030a }, forCodepoint(0x212b).?);",
            "    try testing.expectEqualSlices(u21, &.{ 0x0066, 0x0069 }, compatibilityForCodepoint(0xfb01).?);",
            "    try testing.expectEqualSlices(u21, &.{ 0x0020, 0x0308 }, compatibilityForCodepoint(0x00a8).?);",
            "    try testing.expect(markLeadingForCodepoint(0x1ea4) == null);",
            "    try testing.expect(forCodepoint('A') == null);",
            "    try testing.expect(compatibilityForCodepoint('A') == null);",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    source = Path(sys.argv[1])
    canonical, compatibility, categories = parse(source)
    # U+1CCFA is new in Unicode 17. Pinning this sentinel prevents silently
    # regenerating tables from an older system UCD.
    if 0x1CCFA not in categories:
        raise SystemExit("expected Unicode 17.0 UnicodeData.txt")
    canonical_recursive = expand_all(canonical)
    compatibility_all = dict(canonical)
    compatibility_all.update(compatibility)
    compatibility_recursive = expand_all(compatibility_all)
    Path(sys.argv[2]).write_text(
        render(
            canonical,
            canonical_recursive,
            compatibility_all,
            compatibility_recursive,
            categories,
        ),
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
