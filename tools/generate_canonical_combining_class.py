#!/usr/bin/env python3
"""Generate the compact Canonical_Combining_Class page table.

Usage:
    tools/generate_canonical_combining_class.py \
        path/to/extracted/DerivedCombiningClass.txt \
        src/unicode/canonical/combining_class.zig

The input is the Unicode Character Database's DerivedCombiningClass.txt. The
generator drops the default class zero, sorts the remaining property ranges,
and writes both a deduplicated byte page table (`combining_class.bin`) and the
small Zig decoder next to it.
"""

from __future__ import annotations

import hashlib
import re
import struct
import sys
from pathlib import Path

INPUT_SHA256 = "191463abfbd202703c6fd6776a92a23ac44ec65e0476a7f95aa91ca492cef29b"
PAGE_SIZE = 256
PAGE_COUNT = 0x1100

LINE_RE = re.compile(
    r"^([0-9A-Fa-f]+)(?:\.\.([0-9A-Fa-f]+))?\s*;\s*(\d+)\b"
)


def checked_text(path: Path) -> str:
    data = path.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != INPUT_SHA256:
        raise SystemExit(
            f"{path}: expected Unicode 17 source SHA-256 {INPUT_SHA256}, "
            f"found {actual}"
        )
    return data.decode("utf-8")


def parse_ranges(text: str) -> tuple[str, list[tuple[int, int, int]]]:
    version = "unknown"
    ranges: list[tuple[int, int, int]] = []
    for line in text.splitlines():
        if line.startswith("# DerivedCombiningClass-"):
            version = line.removeprefix("# DerivedCombiningClass-").removesuffix(".txt")
        match = LINE_RE.match(line)
        if match is None:
            continue
        first = int(match.group(1), 16)
        last = int(match.group(2) or match.group(1), 16)
        combining_class = int(match.group(3))
        if combining_class != 0:
            ranges.append((first, last, combining_class))

    ranges.sort()
    merged: list[tuple[int, int, int]] = []
    for first, last, combining_class in ranges:
        if first > last or last > 0x10FFFF or combining_class > 0xFF:
            raise ValueError(f"invalid CCC range: {first:X}..{last:X}; {combining_class}")
        if merged and first <= merged[-1][1]:
            raise ValueError(
                f"overlapping CCC ranges: {merged[-1][0]:X}..{merged[-1][1]:X} "
                f"and {first:X}..{last:X}"
            )
        if (
            merged
            and first == merged[-1][1] + 1
            and combining_class == merged[-1][2]
        ):
            previous_first, _, previous_class = merged[-1]
            merged[-1] = (previous_first, last, previous_class)
        else:
            merged.append((first, last, combining_class))
    return version, merged


def build_values(ranges: list[tuple[int, int, int]]) -> list[int]:
    values = [0] * 0x110000
    for first, last, combining_class in ranges:
        for codepoint in range(first, last + 1):
            values[codepoint] = combining_class
    return values


def build_page_table(values: list[int]) -> tuple[list[int], list[bytes]]:
    pages: list[bytes] = []
    page_index: dict[bytes, int] = {}
    index: list[int] = []
    for page in range(PAGE_COUNT):
        chunk = bytes(values[page * PAGE_SIZE : (page + 1) * PAGE_SIZE])
        slot = page_index.get(chunk)
        if slot is None:
            slot = len(pages)
            if slot > 0xFFFF:
                raise SystemExit("combining-class page table exceeds u16 index space")
            page_index[chunk] = slot
            pages.append(chunk)
        index.append(slot)
    return index, pages


def render_blob(version: str, index: list[int], pages: list[bytes]) -> bytes:
    parts = version.split(".")
    if len(parts) != 3 or not all(part.isdigit() for part in parts):
        raise SystemExit(f"invalid Unicode version: {version}")
    major, minor, patch = (int(part) for part in parts)
    payload = bytearray(
        struct.pack(
            "<4sBBBBHH",
            b"CJC1",
            1,
            major,
            minor,
            patch,
            PAGE_COUNT,
            len(pages),
        )
    )
    for slot in index:
        payload += struct.pack("<H", slot)
    for page in pages:
        payload += page
    return bytes(payload)


def render_zig(version: str) -> str:
    return "\n".join(
        [
            f"// Generated by tools/generate_canonical_combining_class.py from Unicode {version}.",
            f"// DerivedCombiningClass.txt SHA-256: {INPUT_SHA256}",
            "",
            'const std = @import("std");',
            "",
            'const data = @embedFile("combining_class.bin");',
            "const header_len = 12;",
            "const index_count = readU16(8);",
            "const page_count = readU16(10);",
            "const index_offset = header_len;",
            "const pages_offset = index_offset + @as(usize, index_count) * 2;",
            "",
            "/// Flat table derived from `combining_class.bin` by",
            "/// `tools/unicode/canonical/generate_flat_combining_class.py`. A single load",
            "/// avoids the packed table's dependent index-then-page loads.",
            'const flat = @embedFile("flat_combining_class.bin");',
            "const flat_header_len = 16;",
            "const flat_count = readU32At(flat, 8);",
            "",
            "comptime {",
            '    if (data.len < header_len or !std.mem.eql(u8, data[0..4], "CJC1") or',
            "        data[4] != 1 or data[5] != 17 or data[6] != 0 or data[7] != 0)",
            "    {",
            '        @compileError("invalid Unicode Canonical_Combining_Class data");',
            "    }",
            "    if (index_count != 0x1100 or",
            "        pages_offset + @as(usize, page_count) * 256 != data.len)",
            "    {",
            '        @compileError("invalid Unicode Canonical_Combining_Class data lengths");',
            "    }",
            '    if (flat.len < flat_header_len or !std.mem.eql(u8, flat[0..4], "CJZ8") or',
            "        flat[4] != 1 or flat[5] != 17 or flat[6] != 0 or flat[7] != 0)",
            "    {",
            '        @compileError("invalid flat Canonical_Combining_Class data");',
            "    }",
            "    if (flat_count != 0x110001 or flat_header_len + flat_count != flat.len) {",
            '        @compileError("invalid flat Canonical_Combining_Class data lengths");',
            "    }",
            "}",
            "",
            "/// Return Canonical_Combining_Class for one scalar.",
            "///",
            "/// ASCII, surrogates, and every scalar outside the Unicode range are",
            "/// Not_Reordered (0), so the generator's zero sentinel makes a clamped load",
            "/// match the packed table's validity rule.",
            "pub inline fn forCodepoint(codepoint: u21) u8 {",
            "    const index: usize = @min(",
            "        @as(usize, codepoint),",
            "        @as(usize, flat_count) - 1,",
            "    );",
            "    return flat[flat_header_len + index];",
            "}",
            "",
            "/// Packed-table lookup, kept as the reference for the flat table's test.",
            "fn forCodepointPacked(codepoint: u21) u8 {",
            "    if (codepoint < 0x80 or codepoint > 0x10ffff) return 0;",
            "    const page = @as(usize, codepoint) >> 8;",
            "    const slot = readU16(index_offset + page * 2);",
            "    return data[",
            "        pages_offset + @as(usize, slot) * 256 +",
            "            (@as(usize, codepoint) & 0xff)",
            "    ];",
            "}",
            "",
            "fn readU16(offset: usize) u16 {",
            '    return std.mem.readInt(u16, data[offset..][0..2], .little);',
            "}",
            "",
            "fn readU32At(blob: []const u8, offset: usize) u32 {",
            "    return std.mem.readInt(u32, blob[offset..][0..4], .little);",
            "}",
            "",
            'test "canonical combining classes include Tai Tham marks" {',
            '    const testing = @import("std").testing;',
            "    try testing.expectEqual(@as(u8, 9), forCodepoint(0x1a60));",
            "    try testing.expectEqual(@as(u8, 230), forCodepoint(0x1a7a));",
            "    try testing.expectEqual(@as(u8, 0), forCodepoint(0x1a43));",
            "}",
            "",
            'test "ASCII and out-of-range scalars are Not_Reordered" {',
            '    const testing = @import("std").testing;',
            "    try testing.expectEqual(@as(u8, 0), forCodepoint('A'));",
            "    try testing.expectEqual(@as(u8, 0), forCodepoint(0x110000));",
            "}",
            "",
            'test "flat combining classes match the packed table" {',
            '    const testing = @import("std").testing;',
            "    var codepoint: u32 = 0;",
            "    while (codepoint <= 0x1fffff) : (codepoint += 1) {",
            "        const value: u21 = @intCast(codepoint);",
            "        try testing.expectEqual(forCodepointPacked(value), forCodepoint(value));",
            "    }",
            "}",
            "",
        ]
    )

def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    input_path = Path(sys.argv[1])
    output_path = Path(sys.argv[2])
    text = checked_text(input_path)
    version, ranges = parse_ranges(text)
    index, pages = build_page_table(build_values(ranges))
    output_path.with_name("combining_class.bin").write_bytes(
        render_blob(version, index, pages)
    )
    output_path.write_text(render_zig(version), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
